def compute_popyears():
    """Agent population-years per replicate over the cohort window, plus the
    mean Active TB Prevalence over the same window, from the baseline InsetCharts."""
    tags = pd.read_sql_query("SELECT SIM_ID, Scenario_Code, Run_Number FROM results",
                             sqlite3.connect(str(EXP / "results.db")))
    sims = tags.loc[tags.Scenario_Code == 0].sort_values("Run_Number").SIM_ID.astype(str)
    stat_py, prev = [], []
    for sim in sims:
        f = EXP / sim / "InsetChart.json"
        if not f.exists():
            continue
        with open(f, encoding="utf-8") as fh:
            ch = json.load(fh)
        dt = float(ch["Header"]["Simulation_Timestep"])
        pop = np.asarray(ch["Channels"]["Statistical Population"]["Data"], float)
        pv = np.asarray(ch["Channels"]["Active TB Prevalence"]["Data"], float)
        yr = 1850.0 + np.arange(len(pop)) * dt / 365.0
        m = (yr >= COHORT[0]) & (yr < COHORT[1])
        stat_py.append(float((pop[m] * dt / 365.0).sum()))
        prev.append(float(pv[m].mean() * 1e5))
    out = {"span": f"{COHORT[0]:.0f}-{COHORT[1] - 1:.0f}",
           "rule": "2015.0 <= year < 2025.0 (ten calendar years)",
           "n_replicates": len(stat_py),
           "statistical_person_years_per_replicate": float(np.mean(stat_py)),
           "sampling_rate": SAMPLE_RATE,
           "agent_person_years_per_replicate": float(np.mean(stat_py)) * SAMPLE_RATE,
           "mean_active_tb_prevalence_per_1e5": float(np.mean(prev)),
           "experiment": EXP.name,
           "note": ("ReportEventRecorder counts agents, InsetChart reports the "
                    "statistical population, so episode person-years must be divided "
                    "by the AGENT population-years (statistical x "
                    "Base_Individual_Sample_Rate). All baseline replicates are "
                    "included, including the one that fades out before 1960.")}
    POPYEARS.write_text(json.dumps(out, indent=1), encoding="utf-8")
    print("wrote", POPYEARS, {k: round(v, 1) for k, v in out.items()
                              if isinstance(v, float)})


def plot():
    d_all = pd.read_csv(EPISODES)
    n_rep = d_all.rep.nunique()          # every replicate lived through the window
    d = d_all[(d_all.act_year >= COHORT[0]) & (d_all.act_year < COHORT[1])].copy()
    d["total_days"] = (d.seg_subclin + d.seg_patient + d.seg_dxloop
                       + d.seg_txfail + d.seg_ontx)
    if MERGE_TXFAIL_ONLY:
        d["group"] = d["group"].replace({"TxFailonly": "TestTxfail"})
    print(f"cohort {COHORT[0]:.0f}-{COHORT[1] - 1:.0f}: {len(d):,} episodes; "
          f"{n_rep} replicates in the denominator")
    show = ["NoLooponly", "TestLooponly", "TestTxfail"]

    fig, axes = plt.subplots(2, 2, figsize=(15.5, 11))

    # ---- Panel A: density curves ------------------------------------
    ax = axes[0, 0]
    xs = np.linspace(0, 42, 500)
    for g in show:
        v = d.loc[d.group == g, "total_days"].values / MO
        v = v[np.isfinite(v)]
        y = smooth_density(v, xs)
        ax.plot(xs, y, color=GCOL[g], lw=2.6,
                label=f"{GLAB[g]} — median {np.median(v):.1f} mo")
        ax.fill_between(xs, y, color=GCOL[g], alpha=0.13)
        ax.axvline(np.median(v), color=GCOL[g], ls="--", lw=1.4, alpha=0.85)
    ax.set_xlabel("Per-episode active TB duration (months)", fontsize=16.2)
    ax.set_ylabel("Density", fontsize=16.2)
    ax.set_title("A. Distribution of active TB duration, by loop group",
                 fontsize=18.2, fontweight="bold", loc="left")
    ax.legend(fontsize=14.2, frameon=False, loc="upper center",
              bbox_to_anchor=(0.5, -0.18), ncol=1)
    ax.set_xlim(0, 42)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    ax.grid(alpha=0.25)

    # ---- Panel B: Pareto disparity ----------------------------------
    ax = axes[0, 1]
    tot_n = len(d)
    tot_eff = d.eff_days.sum()
    pop_share, tx_share = [], []
    for g in show:
        sub = d[d.group == g]
        pop_share.append(len(sub) / tot_n * 100)
        tx_share.append(sub.eff_days.sum() / tot_eff * 100)
    x = np.arange(len(show))
    w = 0.38
    ax.bar(x - w / 2, pop_share, w, color="#4292C6", edgecolor="white",
           label="% of active TB episodes")
    ax.bar(x + w / 2, tx_share, w, color="#E34A33", edgecolor="white",
           label="% of infectiousness-weighted burden")
    for xi, (p, t) in enumerate(zip(pop_share, tx_share)):
        ax.text(xi - w / 2, p + 1, f"{p:.0f}%", ha="center", fontsize=14.9,
                fontweight="bold", color="#2171B5")
        ax.text(xi + w / 2, t + 1, f"{t:.0f}%", ha="center", fontsize=14.9,
                fontweight="bold", color="#B30000")
    ratio = tx_share[-1] / pop_share[-1]
    ax.text(len(show) - 1, max(tx_share) * 1.10, f"{ratio:.1f}× burden per episode",
            ha="center", fontsize=15.5, fontweight="bold", color="#B30000")
    ax.set_xticks(x)
    ax.set_xticklabels([GLAB[g].replace(" (single pass)", "").replace(" + ", "\n+ ").replace("Any treatment failure", "Any treatment\nfailure")
                        for g in show], fontsize=14.9)
    ax.set_ylabel("Share (%)", fontsize=16.2)
    ax.set_title("B. Episode share vs infectiousness-weighted burden",
                 fontsize=18.2, fontweight="bold", loc="left")
    ax.set_ylim(0, max(tx_share) * 1.25)
    ax.legend(fontsize=14.2, frameon=False, loc="upper center",
              bbox_to_anchor=(0.5, -0.30), ncol=2)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    ax.grid(axis="y", alpha=0.25)

    # ---- Panels C/D: infectious person-years by delay phase ---------
    agg = d.groupby("group").agg(n=("total_days", "size"),
                                 subclin_d=("subclin", "sum"),
                                 patient_d=("patient", "sum"),
                                 hs_d=("hs", "sum")).reindex(show)
    per_person = agg[["subclin_d", "patient_d", "hs_d"]].div(agg.n, axis=0) / 365.0
    # Panel D is a rate, not a count: person-years generated by the cohort
    # divided by the agent population-years of the same ten calendar years
    # (statistical population-years x 5% sampling rate; see compute_popyears).
    with open(POPYEARS, encoding="utf-8") as fh:
        PY = json.load(fh)
    POP_YEARS = PY["agent_person_years_per_replicate"]
    total_py = (agg[["subclin_d", "patient_d", "hs_d"]]
                / 365.0 / n_rep / POP_YEARS * 1e5)

    for ax, tab, ttl, ylab in [
            (axes[1, 0], per_person, "C. Per-episode burden by delay phase",
             "Active TB person-years per episode"),
            (axes[1, 1], total_py, "D. Population burden by delay phase",
             "Active TB person-years generated\nper 100,000 population per year")]:
        bottom = np.zeros(len(show))
        for col, lab, colr in PHASE:
            vals = tab[col].values
            ax.bar(np.arange(len(show)), vals, 0.62, bottom=bottom, label=lab,
                   color=colr, edgecolor="white")
            bottom += vals
        for xi, v in enumerate(bottom):
            ax.text(xi, v * 1.02, f"{v:,.2f}" if v < 10 else f"{v:,.0f}",
                    ha="center", fontsize=14.2, fontweight="bold")
        # the health-system-delay segment is the quantity the text discusses
        # (64% of person-time after the first test; four fifths of the
        # treatment-failure group, a quarter of the no-loop group), so its
        # value is printed inside the purple segment
        hs_vals = tab["hs_d"].values
        ymax = bottom.max() * 1.18
        for xi, (hv, top) in enumerate(zip(hs_vals, bottom)):
            small = hv < 0.12 * ymax          # thin segment: smaller type, no clash with the total
            ax.text(xi, top - hv / 2, f"{hv:,.2f}" if top < 10 else f"{hv:,.0f}",
                    ha="center", va="center", fontsize=11.5 if small else 13.5,
                    color="white", fontweight="bold")
        ax.set_xticks(np.arange(len(show)))
        ax.set_xticklabels([GLAB[g].replace(" (single pass)", "").replace(" + ", "\n+ ").replace("Any treatment failure", "Any treatment\nfailure")
                            for g in show], fontsize=14.9)
        ax.set_ylabel(ylab, fontsize=16.2)
        ax.set_title(ttl, fontsize=18.2, fontweight="bold", loc="left")
        ax.set_ylim(0, bottom.max() * 1.18)
        ax.legend(fontsize=14.2, frameon=False, title="Delay phase", title_fontsize=14.2,
                  loc="upper center", bbox_to_anchor=(0.5, -0.22), ncol=3)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
        ax.grid(axis="y", alpha=0.25)

    plt.tight_layout(h_pad=3.0)
    p = OUT / "Figure3_loop_group_burden.png"
    plt.savefig(p, dpi=300, bbox_inches="tight", facecolor="white")
    plt.close()
    print("saved", p)

    print("\nPanel A medians (months):")
    for g in sorted(d.group.unique()):
        v = d.loc[d.group == g, "total_days"].values / MO
        e = d.loc[d.group == g, "eff_days"].values / MO
        print(f"  {g:14s} median {np.median(v):5.1f}  mean {v.mean():5.1f}  "
              f"median effective {np.median(e):5.1f}  n={len(v):,}")
    print("\nPanel B shares:")
    for g, p_, t_ in zip(show, pop_share, tx_share):
        print(f"  {g:14s} population {p_:5.1f}%   transmission {t_:5.1f}%")
    print(f"  compound-group concentration: {ratio:.3f}x")
    print("\nPanel D (person-years per 100,000 per year):")
    print(total_py.round(1).assign(total=total_py.sum(axis=1).round(1)).to_string())
    print(f"  cohort total {total_py.values.sum():.1f} vs mean Active TB Prevalence "
          f"{PY['mean_active_tb_prevalence_per_1e5']:.1f} per 100,000 over the window")
    print(f"  share of active TB person-time (unweighted) after the first test: "
          f"{d.hs.sum() / (d.hs.sum() + d.patient.sum() + d.subclin.sum()):.4f}")
    pd_groups = {}
    for g in show:
        pd_groups[g] = {c: float(total_py.loc[g, c]) for c in total_py.columns}
        pd_groups[g]["total"] = float(total_py.loc[g].sum())
    summary = {"cohort": PY["span"], "merge_txfail_only": MERGE_TXFAIL_ONLY,
               "n_episodes": int(len(d)), "n_reps_denominator": int(n_rep),
               "panelB": {g: {"episode_share": p_ / 100, "burden_share": t_ / 100}
                          for g, p_, t_ in zip(show, pop_share, tx_share)},
               "concentration": float(ratio),
               "panelD_per1e5": pd_groups,
               "panelD_total_all_groups": float(
                   (d[["subclin", "patient", "hs"]].sum().sum()) / 365.0 / n_rep / POP_YEARS * 1e5),
               "phase_split_per1e5": {c: float(d[c].sum() / 365.0 / n_rep / POP_YEARS * 1e5)
                                      for c in ("subclin", "patient", "hs")},
               "share_after_first_test": float(
                   d.hs.sum() / (d.hs.sum() + d.patient.sum() + d.subclin.sum())),
               "mean_active_tb_prevalence_per_1e5": PY["mean_active_tb_prevalence_per_1e5"]}
    (DATA / "figure3_values.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print("wrote analysis/derived/figure3_values.json")


