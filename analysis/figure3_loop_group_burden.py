def smooth_density(v, xs, bw=None):
    """Gaussian KDE via a fine histogram convolved with a Gaussian kernel.

    Equivalent to scipy.stats.gaussian_kde for large n but far cheaper, and it
    avoids a scipy dependency (not installed in this environment).
    """
    v = np.asarray(v, float)
    v = v[np.isfinite(v)]
    if bw is None:                       # Silverman's rule
        sd = v.std(ddof=1)
        iqr = np.subtract(*np.percentile(v, [75, 25]))
        sigma = min(sd, iqr / 1.349) if iqr > 0 else sd
        bw = 0.9 * sigma * len(v) ** (-0.2)
    lo, hi = xs[0], xs[-1]
    nb = 2000
    edges = np.linspace(lo, hi, nb + 1)
    cnt, _ = np.histogram(v, bins=edges)
    centers = 0.5 * (edges[1:] + edges[:-1])
    step = centers[1] - centers[0]
    half = max(1, int(np.ceil(4 * bw / step)))
    k = np.exp(-0.5 * ((np.arange(-half, half + 1) * step) / bw) ** 2)
    k /= k.sum() * step
    dens = np.convolve(cnt / len(v), k, mode="same")
    return np.interp(xs, centers, dens)
